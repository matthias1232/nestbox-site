"""Tests for the size guard on a build request.

The Dockerfile is generated by the control API, never typed by a person, and
the desktop pack embeds its start, display and desktop-control scripts in it as
base64. The guard therefore has to sit above a real desktop image; a smaller
cap refuses the pack while the build itself would have worked.

`app.main` imports FastAPI and the Docker client at module scope. Both are part
of the runner image, which is where these tests run.
"""
from __future__ import annotations

import unittest

from pydantic import ValidationError

from app.main import MAX_DOCKERFILE_BYTES, BuildRequest

TAG = "nestbox-recipe/desktop-claude:" + "a" * 64


class SizeGuardTests(unittest.TestCase):
    def test_a_desktop_sized_dockerfile_is_accepted(self):
        # 120 KB is the size the desktop Dockerfile reached once the MCP script
        # was part of it; the smaller cap refused it.
        dockerfile = "# Generated by Nestbox from recipe 'desktop-claude'.\n" + "A" * 120_000
        accepted = BuildRequest(tag=TAG, dockerfile=dockerfile)
        self.assertEqual(len(accepted.dockerfile), len(dockerfile))

    def test_a_runaway_body_is_refused(self):
        with self.assertRaises(ValidationError):
            BuildRequest(tag=TAG, dockerfile="A" * (MAX_DOCKERFILE_BYTES + 1))

    def test_an_empty_dockerfile_is_refused(self):
        with self.assertRaises(ValidationError):
            BuildRequest(tag=TAG, dockerfile="")


if __name__ == "__main__":
    unittest.main()
